package com.codearena.enums;

/**
 * Represents the role assigned to a user in the CodeArena platform.
 * <ul>
 *     <li>{@link #USER} — Standard platform user who can solve problems and submit code.</li>
 *     <li>{@link #ADMIN} — Administrator who can create/manage problems and moderate the platform.</li>
 * </ul>
 */
public enum Role {
    USER,
    ADMIN
}
